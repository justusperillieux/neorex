vim.opt.rtp:prepend(vim.env.WORKSPACE_TEST_RUNTIME)
local theme = require('neorex.theme')
vim.api.nvim_set_hl(0, 'Normal', { fg = '#112233', bg = '#445566' })
theme.setup(false)
assert(vim.api.nvim_get_hl(0, { name = 'Normal' }).bg == 0x445566, 'disabled theme must preserve the user colorscheme')
assert(vim.fn.exists(':NeorexTheme') == 0)
local key, color = theme.parse('\27]4;0;rgb:1111/2222/3333\27\\')
assert(key == 0 and color == '#112233')
key, color = theme.parse('\27]10;rgb:ff/ee/dd\7')
assert(key == 'foreground' and color == '#ffeedd')
assert(theme.parse('\27]999;rgb:ff/ee/dd\7') == nil)
assert(not theme.apply({ foreground = '#ffffff' }), 'incomplete responses must not replace the colorscheme')
theme.setup(true)
for _, sequence in ipairs({ '\27]10;rgb:dddd/eeee/ffff\7', '\27]11;rgb:1111/2222/3333\7', '\27]4;2;rgb:4444/aaaa/6666\7' }) do
  vim.api.nvim_exec_autocmds('TermResponse', { data = { sequence = sequence } })
end
assert(vim.wait(500, function() return vim.g.colors_name == 'neorex-rex' end, 10))
assert(vim.api.nvim_get_hl(0, { name = 'Normal' }).bg == 0x112233)
assert(vim.api.nvim_get_hl(0, { name = 'Normal' }).fg == 0xddeeff)
assert(vim.api.nvim_get_hl(0, { name = 'String' }).fg == 0x44aa66)
assert(vim.g.terminal_color_2 == '#44aa66' and vim.o.background == 'dark')
theme.apply({ foreground = '#222222', background = '#ffffff' })
assert(vim.o.background == 'light')
vim.cmd('qa!')
